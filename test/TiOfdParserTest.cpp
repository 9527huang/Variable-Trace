TEST_F(TiOfdParserTest, aStructureHasNoValueOfItsOwnSoItsFieldsAreReported)
{
	TiOfdParser parser(nullptr, nullptr);
	parser.parseDump(dump, "dump.xml");

	const IElfParser::SymbolMap symbols = parser.getParsedData();

	EXPECT_EQ(symbols.count("origin"), 0u);

	ASSERT_EQ(symbols.count("origin.x"), 1u);
	ASSERT_EQ(symbols.count("origin.y"), 1u);

	EXPECT_EQ(symbols.at("origin.x").address, 0x12000u);
	EXPECT_EQ(symbols.at("origin.x").type, Variable::Type::U16);

	/* The second field sits two address units into the structure, which is four
	   bytes the probe has to walk. */
	EXPECT_EQ(symbols.at("origin.y").address, 0x12004u);
	EXPECT_EQ(symbols.at("origin.y").type, Variable::Type::I16);
}

TEST_F(TiOfdParserTest, aStructureInsideAStructureIsFollowed)
{
	TiOfdParser parser(nullptr, nullptr);
	parser.parseDump(dump, "dump.xml");

	const IElfParser::SymbolMap symbols = parser.getParsedData();

	ASSERT_EQ(symbols.count("segment.from.x"), 1u);
	ASSERT_EQ(symbols.count("segment.from.y"), 1u);
	ASSERT_EQ(symbols.count("segment.to.x"), 1u);
	ASSERT_EQ(symbols.count("segment.to.y"), 1u);

	EXPECT_EQ(symbols.at("segment.from.x").address, 0x12200u);
	EXPECT_EQ(symbols.at("segment.from.y").address, 0x12204u);

	/* The second structure sits three units in, six bytes, and each of its
	   fields is reported with its own offset added to that. */
	EXPECT_EQ(symbols.at("segment.to.x").address, 0x12206u);
	EXPECT_EQ(symbols.at("segment.to.y").address, 0x1220au);

	EXPECT_EQ(symbols.at("segment.to.y").type, Variable::Type::I16);
}

