TEST_F(TiOfdParserTest, aToolThatIsNotThereIsRefusedBeforeAnythingIsRead)
{
	TiOfdParser parser(nullptr, nullptr);
	parser.setToolCommand(absentTool);

	std::string reason;

	EXPECT_FALSE(parser.checkAvailability(reason));
	EXPECT_EQ(reason, "NOT FOUND. Please set the ofd2000 path manually");
	EXPECT_EQ(parser.getLastErrorMsg(), reason);
}

TEST_F(TiOfdParserTest, aToolThatIsThereIsAcceptedAndClearsTheMessage)
{
	TiOfdParser parser(nullptr, nullptr);
	parser.setToolCommand(absentTool);

	std::string reason;
	EXPECT_FALSE(parser.checkAvailability(reason));

	parser.setToolCommand(file.string());

	EXPECT_TRUE(parser.checkAvailability(reason));
	EXPECT_EQ(parser.getLastErrorMsg(), "");
}

