TEST_F(TiOfdParserTest, theSizeOfAnArrayIsReadFromItsElementCount)
{
	/* The count can be stated as a number of elements or as the last index. */
	VariableHandler handler;

	auto third = std::make_shared<Variable>("third");
	third->setTrackedName("small[3]");
	handler.addVariable(third);

	auto past = std::make_shared<Variable>("past");
	past->setTrackedName("small[4]");
	handler.addVariable(past);

	TiOfdParser parser(&handler, nullptr);
	parser.parseDump(dump, "dump.xml");

	ASSERT_TRUE(parser.updateVariableMap(""));

	EXPECT_TRUE(third->getIsFound());
	EXPECT_EQ(third->getAddress(), 0x2206u);
	EXPECT_EQ(third->getType(), Variable::Type::U16);

	EXPECT_FALSE(past->getIsFound());
}

TEST_F(TiOfdParserTest, anElementOfAnArrayIsAnsweredByArithmetic)
{
	VariableHandler handler;

	auto fifth = std::make_shared<Variable>("fifth");
	fifth->setTrackedName("buffer[5]");
	handler.addVariable(fifth);

	auto beyond = std::make_shared<Variable>("beyond");
	beyond->setTrackedName("buffer[16]");
	handler.addVariable(beyond);

	/* The array itself has no address: only its elements do. */
	auto whole = std::make_shared<Variable>("whole");
	whole->setTrackedName("buffer");
	handler.addVariable(whole);

	auto malformed = std::make_shared<Variable>("malformed");
	malformed->setTrackedName("buffer[abc]");
	handler.addVariable(malformed);

	auto kept = std::make_shared<Variable>("kept");
	kept->setTrackedName("counter");
	kept->setShouldUpdateFromElf(false);
	kept->setAddress(0x1234);
	kept->setIsFound(true);
	handler.addVariable(kept);

	TiOfdParser parser(&handler, nullptr);
	parser.parseDump(dump, "dump.xml");
	ASSERT_TRUE(parser.updateVariableMap(""));

	EXPECT_TRUE(fifth->getIsFound());
	EXPECT_EQ(fifth->getAddress(), 0x200au);
	EXPECT_EQ(fifth->getType(), Variable::Type::U16);

	EXPECT_FALSE(beyond->getIsFound());
	EXPECT_FALSE(whole->getIsFound());
	EXPECT_FALSE(malformed->getIsFound());

	/* A variable marked as not updated from the symbol file is left as it was,
	   including the address it already had. */
	EXPECT_TRUE(kept->getIsFound());
	EXPECT_EQ(kept->getAddress(), 0x1234u);
}

TEST_F(TiOfdParserTest, theEntriesTheViewerCannotReadAreLeftOut)
{
	TiOfdParser parser(nullptr, nullptr);
	parser.parseDump(dump, "dump.xml");

	const IElfParser::SymbolMap symbols = parser.getParsedData();

	/* A pointer holds an address, which the viewer has nothing to draw. */
	EXPECT_EQ(symbols.count("pBuf"), 0u);

	/* A name that only declares a variable defined in another file has no
	   address in this one. */
	EXPECT_EQ(symbols.count("declaredOnly"), 0u);

	/* A location in a register, and one that is an index rather than an
	   address, have no address that can be read before the program runs. */
	EXPECT_EQ(symbols.count("inRegister"), 0u);
	EXPECT_EQ(symbols.count("indexed"), 0u);

	/* Zero is not an address, it is what a field that was never filled in
	   holds. */
	EXPECT_EQ(symbols.count("atZero"), 0u);

	/* No type, or no name, or a width the viewer has no representation for. */
	EXPECT_EQ(symbols.count("noType"), 0u);
	EXPECT_EQ(symbols.count("wide"), 0u);
	EXPECT_EQ(symbols.count(""), 0u);

	/* The element type of the last array is a structure, and an array of
	   structures would have to be expanded element by element. */
	EXPECT_EQ(symbols.count("points[0]"), 0u);
}

