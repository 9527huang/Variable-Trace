TEST(TiOfdParserValueTest, oneAddressUnitIsTwoBytes)
{
	EXPECT_EQ(TiOfdParser::bytesPerAddressUnit, 2u);
	EXPECT_EQ(TiOfdParser::toByteAddress(0), 0u);
	EXPECT_EQ(TiOfdParser::toByteAddress(1), 2u);
	EXPECT_EQ(TiOfdParser::toByteAddress(0x8000), 0x10000u);
}

TEST(TiOfdParserValueTest, theAddressOperationCarriesTheAddress)
{
	uint64_t address = 0;

	ASSERT_TRUE(TiOfdParser::decodeLocation("DW_OP_addr 0x8000", address));
	EXPECT_EQ(address, 0x8000u);

	/* Without the prefix the number is still read as hexadecimal, which is how
	   debug information is printed. */
	ASSERT_TRUE(TiOfdParser::decodeLocation("DW_OP_addr 8000", address));
	EXPECT_EQ(address, 0x8000u);
}

TEST(TiOfdParserValueTest, theSeparatorsAPrinterMayAddAreAccepted)
{
	uint64_t address = 0;

	ASSERT_TRUE(TiOfdParser::decodeLocation("DW_OP_addr: 0x1234", address));
	EXPECT_EQ(address, 0x1234u);

	ASSERT_TRUE(TiOfdParser::decodeLocation("DW_OP_addr | 0x40", address));
	EXPECT_EQ(address, 0x40u);
}

TEST(TiOfdParserValueTest, anIndexedAddressIsNotAnAddress)
{
	/* The operand indexes a section this walk does not open, so the entry is
	   dropped rather than guessed at. */
	uint64_t address = 0;

	EXPECT_FALSE(TiOfdParser::decodeLocation("DW_OP_addrx 0x3", address));
}

TEST(TiOfdParserValueTest, aLocationInARegisterIsNotAnAddress)
{
	uint64_t address = 0;

	EXPECT_FALSE(TiOfdParser::decodeLocation("DW_OP_reg5", address));
	EXPECT_FALSE(TiOfdParser::decodeLocation("DW_OP_fbreg -8", address));
	EXPECT_FALSE(TiOfdParser::decodeLocation("", address));
}

TEST(TiOfdParserValueTest, anOperationWithNoNumberUnderItIsNotAnAddress)
{
	uint64_t address = 0;

	EXPECT_FALSE(TiOfdParser::decodeLocation("DW_OP_addr", address));
}

TEST(TiOfdParserValueTest, anOperationWhoseNameStartsWithAnotherIsNotAMatch)
{
	/* The first operation name is a prefix of the second, so a match that runs
	   into another name character does not count. */
	uint64_t address = 0;

	EXPECT_FALSE(TiOfdParser::decodeLocation("DW_OP_address 0x10", address));
}

