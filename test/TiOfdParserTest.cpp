TEST_F(TiOfdParserTest, everyScalarInTheDocumentIsReported)
{
	TiOfdParser parser(nullptr, nullptr);
	parser.parseDump(dump, "dump.xml");

	const IElfParser::SymbolMap symbols = parser.getParsedData();

	/* Eleven: three scalars, one of them reached through a typedef, one
	   enumeration, six fields of two structures, and one element of each of two
	   arrays. Everything else in the document is something the viewer cannot
	   read, and is listed in the test below. */
	ASSERT_EQ(symbols.size(), 11u);

	const auto scalars = {"counter", "typed", "state", "buffer[0]", "small[0]"};

	for (const char* name : scalars)
		EXPECT_EQ(symbols.count(name), 1u) << name;
}

TEST_F(TiOfdParserTest, aScalarIsReportedAtItsByteAddress)
{
	/* The file says 0x8000, which is 0x10000 once the address units are turned
	   into the bytes the probe addresses. */
	TiOfdParser parser(nullptr, nullptr);
	parser.parseDump(dump, "dump.xml");

	const IElfParser::SymbolMap symbols = parser.getParsedData();

	ASSERT_EQ(symbols.count("counter"), 1u);
	EXPECT_EQ(symbols.at("counter").address, 0x10000u);

	/* Two address units is a 32 bit number on this family, not a 16 bit one. */
	EXPECT_EQ(symbols.at("counter").type, Variable::Type::U32);
}

